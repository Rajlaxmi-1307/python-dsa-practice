# Python Variables

name = "Raj"
age = 21
height = 5.8
is_student = True

print("Name:", name)
print("Age:", age)
print("Height:", height)
print("Student:", is_student)

# Multiple variable assignment
a, b, c = 10, 20, 30

print("A:", a)
print("B:", b)
print("C:", c)

# Swapping two variables
a, b = b, a

print("After swapping:")
print("A:", a)
print("B:", b)
